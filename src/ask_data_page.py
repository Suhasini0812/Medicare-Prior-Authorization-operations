"""Manager-facing question form and visible, scoped calculation evidence."""

import os

import pandas as pd
import streamlit as st

from src.assistant_flow import answer_question, configured_model


def render_ask_data(cohort, *, snapshot_date: str, period_label: str, scope_key: tuple) -> None:
    st.markdown(
        "**Example questions**\n"
        "- How many requests are Pending, Approved, or Denied?\n"
        "- Which category has the largest Pending workload?\n"
        "- Which category has the highest Pending rate?\n"
        "- What is the Pending count and rate for Cardiology?"
    )
    ready = bool(os.getenv("OPENAI_API_KEY", "").strip())
    if not ready:
        st.caption("Add OPENAI_API_KEY in Replit Secrets to enable answers.")
    if st.session_state.get("ask_scope") != scope_key:
        st.session_state.pop("ask_result", None)
        st.session_state["ask_scope"] = scope_key
    with st.form("ask_data_form"):
        st.caption("Synthetic data only—do not enter member, clinical, or request details.")
        question = st.text_area("Question", max_chars=1000, placeholder="Which category has the highest Pending rate?")
        submitted = st.form_submit_button("Ask the Data", disabled=not ready, key="ask_submit")
    if submitted:
        with st.spinner("Understanding the question and checking Python calculations…"):
            try:
                result = answer_question(question, cohort, configured_model())
            except Exception:
                result = {"status": "error", "evidence": None, "answer": "Could not initialize the model. Check the API configuration and try again."}
            st.session_state["ask_result"] = result
    result = st.session_state.get("ask_result")
    if result is None:
        st.caption("No question answered yet. Choose a reporting scope and enter a question above.")
        return
    st.subheader("Answer and supporting calculation")
    st.caption(f"Status snapshot date: {snapshot_date} · Received-date reporting period: {period_label}")
    if result["status"] == "error":
        st.error(result["answer"])
    elif result["status"] in ("setup", "empty", "unsupported", "no_results"):
        st.info(result["answer"])
    else:
        st.write(result["answer"])
        evidence = result["evidence"]
        st.dataframe(
            pd.DataFrame(evidence["rows"]), hide_index=True, width="stretch",
            column_config={
                "Rate": st.column_config.NumberColumn("Share of Total Requests", format="%.1f%%"),
                "Pending rate": st.column_config.NumberColumn("Pending rate", format="%.1f%%"),
            },
        )
        st.caption("Calculation: count ÷ denominator × 100. Values are calculated by Python, not generated by the model.")
